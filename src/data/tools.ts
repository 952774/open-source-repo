export interface Tool {
  id: string;
  name: string;
  /** 英文名（中文名工具必填，纯英文名可省略） */
  nameEn?: string;
  category: CategoryId;
  /** 一句话说明它是什么 */
  description: string;
  /** 什么情况下用它（用于场景推荐与搜索） */
  scenarios: string[];
  license: string;
  openSource: boolean;
  /** winget 包 ID —— 安装引擎的唯一依据 */
  wingetId: string;
  /** 安装后用于验证是否成功的命令（可选，CLI 工具有） */
  verify?: string;
  /** 展示用图标（emoji，避免外部资源依赖） */
  icon: string;
  /** 图标在线地址（可选，优先用 simple-icons CDN） */
  iconUrl?: string;
  /** 界面截图 URL 列表（可选；为空时详情页显示占位与官网链接，不编造图片） */
  screenshots?: string[];
  tags: string[];
  homepage: string;
  /** GitHub 仓库地址 */
  repo: string;
  /** GitHub star 数（展示用字符串，"—" 表示未取到） */
  stars: string;
  /** 最近一次提交/发布日 YYYY-MM-DD（"—" 表示未取到） */
  lastUpdate: string;
  /** 是否首批推荐（首页优先展示） */
  featured?: boolean;
}

